    /// Reference keys from PyNaCl (the same libsodium the spec's vector generator uses).
    func test_argon2idMatchesLibsodiumReference() throws {
        let a = try VaultCrypto.key(code: "correct horse battery staple", groupId: "group_123")
        XCTAssertEqual(Hex.encode(a.withUnsafeBytes { Array($0) }), "bc692b156179f11c2ff5b9fc219447ae0611f174612c137c7b06fc4dbf48eddd")
        let b = try VaultCrypto.key(code: "the decoy family phrase", groupId: "g-1")
        XCTAssertEqual(Hex.encode(b.withUnsafeBytes { Array($0) }), "71ae758e4e780697b59e0b18150b05ac964a26da3be40a7e7d35cfb1b0ff19ed")
    }

    func test_slotIsExactly512_andPaddedTo484() throws {
        let sealed = try VaultCrypto.seal(item(), key: key(k1))
        XCTAssertEqual(sealed.count, 512)
        XCTAssertEqual(VaultCrypto.padded(item())?.count, 484)
        XCTAssertEqual(VaultCrypto.padded(item(name: "a/b/c.pdf"))?.count, 484, "slashes aren't escaped")
        XCTAssertEqual(VaultCrypto.open(sealed, key: key(k1)), item().withPadIgnored(VaultCrypto.open(sealed, key: key(k1))!.pad))
        XCTAssertNil(VaultCrypto.open(sealed, key: key(k2)))
        let long = VaultCrypto.fitName(item(name: String(repeating: "x", count: 600)))
        XCTAssertNotNil(VaultCrypto.padded(long), "a long name is shortened to fit")
    }

    func test_anyOtherCodeOpensAnEmptyVault_andEverythingIsRandomUntilWritten() {
        let container = VaultCrypto.randomContainer()
        XCTAssertEqual(container.count, 131_072)
        XCTAssertTrue(VaultCrypto.openAll(container, key: key(k1)).isEmpty)
        let written = VaultCrypto.write(item(), into: container, key: key(k1))!
        XCTAssertEqual(VaultCrypto.openAll(written, key: key(k1)).map(\.payload.fileId), [item().fileId])
        XCTAssertEqual(VaultCrypto.openAll(written, key: key(k1)).first?.slots.count, 2, "two replicas")
        XCTAssertTrue(VaultCrypto.openAll(written, key: key(k2)).isEmpty, "another code sees nothing")
        XCTAssertEqual(written.count, container.count)
    }

    func test_newestRevisionWins_andDeletionIsAStateNotAnErasure() {
        let first = VaultCrypto.write(item(), into: VaultCrypto.randomContainer(), key: key(k1))!
        let slots = VaultCrypto.openAll(first, key: key(k1))[0].slots
        let removed = VaultCrypto.write(item(revision: 9, state: VaultSlotPayload.reclaimed), into: first, key: key(k1), existing: slots)!
        let items = VaultCrypto.openAll(removed, key: key(k1))
        XCTAssertEqual(items.count, 1)
        XCTAssertFalse(items[0].isActive)
        XCTAssertEqual(items[0].slots, slots, "rewritten in place, so it can be undone")
    }

    func test_twoVaultsShareOneContainer() {
        var c = VaultCrypto.randomContainer()
        c = VaultCrypto.write(item("a"), into: c, key: key(k1))!
        c = VaultCrypto.write(item("b"), into: c, key: key(k2))!
        XCTAssertEqual(VaultCrypto.openAll(c, key: key(k1)).map(\.id), ["a"])
        XCTAssertEqual(VaultCrypto.openAll(c, key: key(k2)).map(\.id), ["b"])
    }
}

final class VaultStoreTests: XCTestCase {
    private var dir: URL!
    override func setUp() { dir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString) }
    override func tearDown() { try? FileManager.default.removeItem(at: dir) }
    private func store() -> VaultStore { VaultStore(directory: dir.appendingPathComponent("vault"), viewRoot: dir.appendingPathComponent("views")) }

    func test_containerExistsFromFirstUse_andIsKept() throws {
        let a = try store().container()
        XCTAssertEqual(a.count, 131_072)
        XCTAssertEqual(try store().container(), a, "the same random container after a restart")
    }

    func test_aWrongSizedContainerIsSetAside_notDeleted() throws {
        let v = dir.appendingPathComponent("vault")
        try FileManager.default.createDirectory(at: v, withIntermediateDirectories: true)
        try Data(repeating: 1, count: 10).write(to: v.appendingPathComponent("container.bin"))
        XCTAssertEqual(try store().container().count, 131_072)
        XCTAssertTrue(FileManager.default.fileExists(atPath: v.appendingPathComponent("container.bin.corrupt").path))
    }

    func test_versionMarkIsPersisted() {
        XCTAssertEqual(store().version, 0)
        store().setVersion(1_800_000_000_123)
        XCTAssertEqual(store().version, 1_800_000_000_123, "a restart doesn't reset it, so an old container can't roll it back")
    }

    func test_chunkBounds() {
        let s = store()
        XCTAssertFalse(s.storeChunk(fileId: "f", index: 0, totalChunks: VaultStore.maxItemChunks + 1, ciphertext: Data([1])), "over 25 MiB")
        XCTAssertFalse(s.storeChunk(fileId: "../x", index: 0, totalChunks: 1, ciphertext: Data([1])))
        XCTAssertTrue(s.storeChunk(fileId: "f", index: 0, totalChunks: 3, ciphertext: Data([1])))
        XCTAssertFalse(s.storeChunk(fileId: "f", index: 1, totalChunks: 4, ciphertext: Data([1])), "the count is fixed once seen")
        XCTAssertFalse(s.storeChunk(fileId: "f", index: 0, totalChunks: 3, ciphertext: Data([1])), "already held")
        XCTAssertTrue(s.storeChunk(fileId: "f", index: 2, totalChunks: 3, ciphertext: Data([3])))
        XCTAssertEqual(s.missing("f", chunkCount: 3), [1])
        XCTAssertEqual(s.servable(VaultChunkRequest(requesterId: "b", fileId: "f", missing: [0, 1, 2, 9], timestamp: 0))?.indices, [0, 2],
                       "serve what's held, nothing else")
        XCTAssertNil(s.servable(VaultChunkRequest(requesterId: "b", fileId: "zzz", missing: [0], timestamp: 0)))
        XCTAssertTrue(store().blob("f").map { $0.held == [0, 2] } ?? false, "held chunks survive a restart")
    }
}

private extension VaultSlotPayload {
    func withPadIgnored(_ pad: String) -> VaultSlotPayload { var p = self; p.pad = pad; return p }
}

/// `vault/repair` sealed like `files/repair` (agreed 2026-10-26), plaintext still read during the changeover.
final class VaultRepairSealingTests: XCTestCase {
    private func group(key: String?) throws -> GroupDefinition {
        let a = try FamilySafeKeyDerivation.deriveIdentity(seed: Array(SHA512.hash(data: Data("a".utf8))))
        return GroupDefinition(groupId: "g", groupName: "F", createdAtEpochMs: 1, creatorMemberId: a.memberId,
                               members: [FamilyMember(memberId: a.memberId, displayName: "a", ed25519PublicKey: a.ed25519PublicKeyHex,
                                                      x25519PublicKey: a.x25519PublicKeyHex, addedAtEpochMs: 1)],
                               version: 1, fileEncryptionKey: key)
    }
    private let request = VaultChunkRequest(requesterId: "ben", fileId: "f", missing: [1, 2], timestamp: 5)

    func test_sealedRoundTrips_andHidesTheRequest() throws {
        let g = try group(key: String(repeating: "cd", count: 32))
        let sealed = try FileCodec.sealMessage(request, group: g)
        XCTAssertFalse(String(decoding: sealed, as: UTF8.self).contains("ben"))
        XCTAssertEqual(FamilyNode.openVaultRequest(sealed, group: g), request)
    }

    func test_plaintextStillReadWhilePhonesUpdate() throws {
        let g = try group(key: String(repeating: "cd", count: 32))
        XCTAssertEqual(FamilyNode.openVaultRequest(try JSONEncoder().encode(request), group: g), request)
    }

    func test_sealedUnderAnotherKeyIsDropped_notReadAsPlaintext() throws {
        let other = try FileCodec.sealMessage(request, group: try group(key: String(repeating: "ef", count: 32)))
        XCTAssertNil(FamilyNode.openVaultRequest(other, group: try group(key: String(repeating: "cd", count: 32))))
    }
}
